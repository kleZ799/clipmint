  // The picker names every language in its own language. A user hunting for
  // their own has to recognise it while the interface is still in one they
  // cannot read, so "Deutsch" is findable in a way that "German" is not.
  const NAMES = {
    en: "English", hi: "हिन्दी", es: "Español",
    pt: "Português", fr: "Français", de: "Deutsch", ja: "日本語",
  };

  const STORE_KEY = "ui-lang";

  // English on a fresh install, always. The browser's own locale is
  // deliberately not consulted: a machine set to another language would
  // otherwise hand a first-run user an interface nobody chose.
  let lang = "en";
  try {
    const saved = localStorage.getItem(STORE_KEY);
    if (saved && (saved === "en" || DICT[saved])) lang = saved;
  } catch (e) { /* private mode: stay on English */ }

  function t(s) {
    if (typeof s !== "string" || lang === "en") return s;
    const table = DICT[lang];
    if (!table) return s;
    const hit = table[s.trim()];
    if (hit === undefined) return s;
    // Preserve whatever padding the caller had around the word.
    const lead = s.match(/^\s*/)[0], tail = s.match(/\s*$/)[0];
    return lead + hit + tail;
  }

  // The English source has to survive translation, or switching hi -> es would
  // be looking up Hindi in the Spanish table and finding nothing. Each node
  // keeps the string it was born with.
  const EN = new WeakMap();

  function englishOf(node, current) {
    if (!EN.has(node)) EN.set(node, current);
    return EN.get(node);
  }

  const SKIP = new Set(["SCRIPT", "STYLE", "TEXTAREA", "CODE", "PRE"]);

  function apply(root) {
    root = root || document.body;
    const walker = document.createTreeWalker(root, NodeFilter.SHOW_TEXT, {
      acceptNode(n) {
        if (!n.nodeValue || !n.nodeValue.trim()) return NodeFilter.FILTER_REJECT;
        if (n.parentElement && SKIP.has(n.parentElement.tagName)) return NodeFilter.FILTER_REJECT;
        return NodeFilter.FILTER_ACCEPT;
      },
    });
    const nodes = [];
    for (let n = walker.nextNode(); n; n = walker.nextNode()) nodes.push(n);
    nodes.forEach((n) => { n.nodeValue = t(englishOf(n, n.nodeValue)); });

    // Attributes a user reads but a text walk never reaches.
    root.querySelectorAll("[placeholder]").forEach((el) => {
      el.placeholder = t(englishOf(el, el.placeholder));
    });
    // A title and a placeholder can sit on the same element, so the title
    // keeps its own cache slot rather than fighting for the WeakMap's.
    root.querySelectorAll("[title]").forEach((el) => {
      if (!el.dataset.enTitle) el.dataset.enTitle = el.title;
      el.title = t(el.dataset.enTitle);
    });
  }

  function set(next) {
    if (next !== "en" && !DICT[next]) return;
    lang = next;
    try { localStorage.setItem(STORE_KEY, next); } catch (e) { /* not fatal */ }
    document.documentElement.lang = next;
    apply(document.body);
  }

  return {
    t, apply, set,
    get lang() { return lang; },
    codes: ["en"].concat(Object.keys(DICT)),
    name: (c) => NAMES[c] || c,
  };
